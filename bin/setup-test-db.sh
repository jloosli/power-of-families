#!/bin/bash

# Test database setup script
# Creates an isolated test database for running tests with proper configuration

set -e

# Default values
TEST_DB_NAME="${TEST_DB_NAME:-wordpress_tests}"
TEST_DB_USER="${TEST_DB_USER:-root}"
TEST_DB_PASSWORD="${TEST_DB_PASSWORD:-password}"
TEST_DB_HOST="${TEST_DB_HOST:-db}"
TEST_DB_CHARSET="${TEST_DB_CHARSET:-utf8mb4}"
TEST_DB_COLLATE="${TEST_DB_COLLATE:-utf8mb4_unicode_ci}"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}🔧 Setting up isolated test database...${NC}"

# Wait for database to be ready
echo -e "${YELLOW}⏳ Waiting for database to be ready...${NC}"
until mysqladmin ping -h"$TEST_DB_HOST" -u"$TEST_DB_USER" -p"$TEST_DB_PASSWORD" --ssl=0 --silent; do
    echo -e "${YELLOW}   Waiting for database...${NC}"
    sleep 2
done

echo -e "${GREEN}✅ Database connection established${NC}"

# Drop existing test database if it exists
echo -e "${YELLOW}🗑️  Dropping existing test database if it exists...${NC}"
mysqladmin -h"$TEST_DB_HOST" -u"$TEST_DB_USER" -p"$TEST_DB_PASSWORD" --ssl=0 drop "$TEST_DB_NAME" --force 2>/dev/null || true

# Create test database with proper charset and collation
echo -e "${YELLOW}📦 Creating test database: $TEST_DB_NAME${NC}"
mysql -h"$TEST_DB_HOST" -u"$TEST_DB_USER" -p"$TEST_DB_PASSWORD" --ssl=0 -e "CREATE DATABASE \`$TEST_DB_NAME\` CHARACTER SET $TEST_DB_CHARSET COLLATE $TEST_DB_COLLATE;"

# Set up test database user with limited permissions (if not using root)
if [ "$TEST_DB_USER" != "root" ]; then
    echo -e "${YELLOW}👤 Setting up test database user...${NC}"
    mysql -h"$TEST_DB_HOST" -u"$TEST_DB_USER" -p"$TEST_DB_PASSWORD" --ssl=0 -e "GRANT ALL PRIVILEGES ON \`$TEST_DB_NAME\`.* TO '$TEST_DB_USER'@'%';"
    mysql -h"$TEST_DB_HOST" -u"$TEST_DB_USER" -p"$TEST_DB_PASSWORD" --ssl=0 -e "FLUSH PRIVILEGES;"
fi

# Create test database configuration file
echo -e "${YELLOW}📝 Creating test database configuration...${NC}"
cat > /tmp/test-db-config.php << EOF
<?php
/**
 * Test Database Configuration
 * Generated by setup-test-db.sh
 */

define('DB_NAME', '$TEST_DB_NAME');
define('DB_USER', '$TEST_DB_USER');
define('DB_PASSWORD', '$TEST_DB_PASSWORD');
define('DB_HOST', '$TEST_DB_HOST');
define('DB_CHARSET', '$TEST_DB_CHARSET');
define('DB_COLLATE', '$TEST_DB_COLLATE');

// Test-specific configuration
define('WP_TESTS_DOMAIN', 'example.org');
define('WP_TESTS_EMAIL', 'admin@example.org');
define('WP_TESTS_TITLE', 'Test Blog');
define('WP_TESTS_URL', 'http://example.org');
define('WP_TESTS_TABLE_PREFIX', 'wptests_');

// Ensure test isolation
define('WP_DEBUG', true);
define('WP_DEBUG_LOG', true);
define('WP_DEBUG_DISPLAY', false);
define('SCRIPT_DEBUG', true);

// Disable external requests during testing
define('WP_HTTP_BLOCK_EXTERNAL', true);
define('WP_ACCESSIBLE_HOSTS', 'api.wordpress.org,*.wordpress.org,*.github.com');
EOF

echo -e "${GREEN}✅ Test database setup complete!${NC}"
echo -e "${BLUE}📊 Database Details:${NC}"
echo -e "   Database: ${GREEN}$TEST_DB_NAME${NC}"
echo -e "   Host: ${GREEN}$TEST_DB_HOST${NC}"
echo -e "   User: ${GREEN}$TEST_DB_USER${NC}"
echo -e "   Charset: ${GREEN}$TEST_DB_CHARSET${NC}"
echo -e "   Collation: ${GREEN}$TEST_DB_COLLATE${NC}"
echo -e "   Config file: ${GREEN}/tmp/test-db-config.php${NC}"

